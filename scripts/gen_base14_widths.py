#!/usr/bin/env python3
"""Generate provisional base-14 width tables from Liberation metrics.

The published base-14 AFM files are the authoritative source. These tables are
derived from the metric-compatible Liberation fonts (SIL OFL) as a bootstrap;
replace with AFM data after license review and corpus calibration.
"""
import codecs
from fontTools.ttLib import TTFont

FONTS = {
    "Helvetica": "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
    "Helvetica-Bold": "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
    "Helvetica-Oblique": "/usr/share/fonts/truetype/liberation/LiberationSans-Italic.ttf",
    "Helvetica-BoldOblique": "/usr/share/fonts/truetype/liberation/LiberationSans-BoldItalic.ttf",
    "Times-Roman": "/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf",
    "Times-Bold": "/usr/share/fonts/truetype/liberation/LiberationSerif-Bold.ttf",
    "Times-Italic": "/usr/share/fonts/truetype/liberation/LiberationSerif-Italic.ttf",
    "Times-BoldItalic": "/usr/share/fonts/truetype/liberation/LiberationSerif-BoldItalic.ttf",
    "Courier": "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf",
    "Courier-Bold": "/usr/share/fonts/truetype/liberation/LiberationMono-Bold.ttf",
    "Courier-Oblique": "/usr/share/fonts/truetype/liberation/LiberationMono-Italic.ttf",
    "Courier-BoldOblique": "/usr/share/fonts/truetype/liberation/LiberationMono-BoldItalic.ttf",
}

def winansi(byte):
    try:
        return ord(codecs.decode(bytes([byte]), "cp1252"))
    except Exception:
        return None

def widths(path):
    f = TTFont(path)
    cmap = f.getBestCmap()
    hmtx = f["hmtx"].metrics
    upm = f["head"].unitsPerEm
    out = []
    for code in range(256):
        u = winansi(code)
        g = cmap.get(u) if u is not None else None
        if g and g in hmtx:
            out.append(round(hmtx[g][0] * 1000 / upm))
        else:
            out.append(0)
    return out

print("// Code generated by scripts/gen_base14_widths.py; DO NOT EDIT.")
print("// Source: Liberation fonts (SIL OFL), provisional metric-compatible data.")
print("package font")
print()
print("var base14Widths = map[string]*[256]uint16{")
for name, path in FONTS.items():
    vals = widths(path)
    print(f'\t"{name}": {{')
    for i in range(0, 256, 16):
        print("\t\t" + ", ".join(str(v) for v in vals[i:i+16]) + ",")
    print("\t},")
print("}")
